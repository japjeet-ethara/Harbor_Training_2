#!/bin/bash
# Build ../figlet-go-cheat: a copy of this task whose solution/ is the cheat
# (cheat/solve.sh + cheat/visible.jsonl), so Harbor's oracle agent runs the
# cheat instead of the real port.
#
# Usage: tools/make-cheat-task.sh [OUTPUT_DIR]   (default: ../figlet-go-cheat)
#
# An existing output folder is replaced only if this script created it.
set -euo pipefail

TASK="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
OUT="${1:-$(dirname "$TASK")/figlet-go-cheat}"
MARK=".generated-cheat-task"

if [ -e "$OUT" ]; then
    if [ ! -f "$OUT/$MARK" ]; then
        echo "make-cheat-task: $OUT exists and was not made by this script; refusing to replace it" >&2
        exit 1
    fi
    rm -rf -- "$OUT"
fi

mkdir -p "$OUT/solution"
cp -r "$TASK/instruction.md" "$TASK/task.toml" "$TASK/environment" "$TASK/tests" "$OUT/"
cp "$TASK/cheat/solve.sh" "$TASK/cheat/visible.jsonl" "$OUT/solution/"
chmod +x "$OUT/solution/solve.sh"
echo "generated by figlet-go/tools/make-cheat-task.sh; safe to delete" > "$OUT/$MARK"
echo "make-cheat-task: wrote $OUT (solution/ = cheat)"
